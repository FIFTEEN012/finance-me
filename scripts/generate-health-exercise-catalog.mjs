import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const DATASET_BASE_URL = 'https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/main'
const DATASET_JSON_URL = `${DATASET_BASE_URL}/data/exercises.json`
const OUTPUT_PATH = path.join(process.cwd(), 'src', 'lib', 'healthExerciseCatalog.generated.ts')

function toAssetUrl(value) {
  return value ? `${DATASET_BASE_URL}/${value}` : ''
}

function getDifficulty(exercise) {
  if (exercise.equipment !== 'body weight') return 'intermediate'

  const name = exercise.name.toLowerCase()
  const advancedTerms = [
    'archer',
    'back lever',
    'burpee',
    'handstand',
    'jump',
    'muscle up',
    'one arm',
    'pull-up',
    'plyo',
    'superman push-up',
  ]

  return advancedTerms.some((term) => name.includes(term)) ? 'intermediate' : 'beginner'
}

function normalizeSteps(exercise) {
  const steps = exercise.instruction_steps?.en
  return Array.isArray(steps) ? steps.filter((step) => typeof step === 'string' && step.trim()) : []
}

function toCatalogItem(exercise) {
  const instructions = normalizeSteps(exercise)

  return {
    id: `exercise-${exercise.id}`,
    sourceId: exercise.id,
    nameTh: exercise.name,
    nameEn: exercise.name,
    bodyPart: exercise.body_part,
    equipment: exercise.equipment,
    target: exercise.target,
    imageUrl: toAssetUrl(exercise.image),
    gifUrl: toAssetUrl(exercise.gif_url),
    instructionsTh: instructions,
    instructionsEn: instructions,
    attribution: exercise.attribution ?? '© Gym visual — https://gymvisual.com/',
    difficulty: getDifficulty(exercise),
  }
}

function renderTypeScript(catalog) {
  return `// Generated by scripts/generate-health-exercise-catalog.mjs
// Source: ${DATASET_JSON_URL}
// Do not edit this file by hand.

import type { HealthCatalogExercise } from '@/types/health'

export const GENERATED_HEALTH_EXERCISE_CATALOG = ${JSON.stringify(catalog, null, 2)} satisfies HealthCatalogExercise[]
`
}

async function main() {
  const response = await fetch(DATASET_JSON_URL)

  if (!response.ok) {
    throw new Error(`Failed to fetch exercises dataset: ${response.status} ${response.statusText}`)
  }

  const rawExercises = await response.json()
  if (!Array.isArray(rawExercises)) {
    throw new Error('Expected exercises dataset to be an array')
  }

  const catalog = rawExercises
    .filter((exercise) => exercise?.id && exercise?.name)
    .map(toCatalogItem)
    .sort((a, b) => a.nameEn.localeCompare(b.nameEn) || a.sourceId.localeCompare(b.sourceId))

  await mkdir(path.dirname(OUTPUT_PATH), { recursive: true })
  await writeFile(OUTPUT_PATH, renderTypeScript(catalog), 'utf8')

  console.log(`Generated ${catalog.length} exercises -> ${path.relative(process.cwd(), OUTPUT_PATH)}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
